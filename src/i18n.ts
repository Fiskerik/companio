export type TextKey = keyof typeof dictionary;
export function t(locale: Locale, key: string) {
  const v = dictionary[key as TextKey];
  return v ? v[locale === 'sv' ? 0 : 1] : key;
}
export function formatDate(value: string, locale: Locale, time = true) {
  return new Intl.DateTimeFormat(locale === 'sv' ? 'sv-SE' : 'en-GB', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    ...(time ? ({ hour: '2-digit', minute: '2-digit' } as const) : {}),
  }).format(new Date(value));
}
export function localInput(date: Date) {
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}
export function parseLocalInput(value: string) {
  if (!/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}$/.test(value)) return '';
  const date = new Date(value.replace(' ', 'T') + ':00');
  return Number.isNaN(date.getTime()) || localInput(date) !== value ? '' : date.toISOString();
}
